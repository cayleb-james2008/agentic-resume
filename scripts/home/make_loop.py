"""Generate site/js/approach/loop-path.js — the "How I work" loop.

    python3 scripts/home/make_loop.py

The reference traced a race circuit; this is our own closed loop through four
stations (Shadow, Understand, Build, Teach) that starts and finishes at the
"Whole company" node. A closed centripetal Catmull-Rom spline through CONTROL,
sampled densely and resampled every 3 units along its length — the same
spacing the lap's pacing and glow were tuned for. Station positions become
distances along the path, so re-timing the lap cannot slide them.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "site/js/approach/loop-path.js"

STEP = 3.0
SAMPLES_PER_SPAN = 40
CONTROL = [
    (470, 560), (350, 500), (340, 380), (430, 290), (560, 250), (720, 200), (880, 170),
    (980, 230), (1010, 360), (940, 470), (980, 590), (860, 650), (700, 610), (580, 600),
]
STATIONS = [(340, 380), (720, 200), (1010, 360), (860, 650)]
# Where each label sits from its node, in map units, so none crosses the ribbon.
LABEL_PLACEMENT = [
    {"dx": 26, "dy": -22, "anchor": "start"},   # Shadow: inside the loop
    {"dx": 0, "dy": -40, "anchor": "middle"},   # Understand: above the top edge
    {"dx": 28, "dy": 10, "anchor": "start"},    # Build: outside the right edge
    {"dx": 0, "dy": 58, "anchor": "middle"},    # Teach: below the bottom edge
]
FINISH_PLACEMENT = {"dx": -30, "dy": -24, "anchor": "end"}

# The map's own frame (spec map-vector.ts) — the one conversion between spaces.
MAP_W, MAP_H, BAND = 2560, 1440, 11.67
ART_TOP, ART_W, ART_H = 2, 1438.43, 796
SCALE_X = MAP_W / ART_W
SCALE_Y = (MAP_H - BAND * 2) / ART_H


def artboard_to_map(x: float, y: float) -> tuple[float, float]:
    return x * SCALE_X, BAND + (y - ART_TOP) * SCALE_Y


def catmull_rom(p0, p1, p2, p3, samples):
    """Centripetal (alpha 0.5) segment from p1 to p2, excluding p2."""
    def knot(t, a, b):
        return t + math.dist(a, b) ** 0.5 or t + 1e-6
    t0 = 0.0
    t1 = knot(t0, p0, p1)
    t2 = knot(t1, p1, p2)
    t3 = knot(t2, p2, p3)
    lerp = lambda a, b, u, v, t: tuple((v - t) / (v - u) * ai + (t - u) / (v - u) * bi for ai, bi in zip(a, b))
    out = []
    for k in range(samples):
        t = t1 + (t2 - t1) * k / samples
        a1 = lerp(p0, p1, t0, t1, t)
        a2 = lerp(p1, p2, t1, t2, t)
        a3 = lerp(p2, p3, t2, t3, t)
        b1 = lerp(a1, a2, t0, t2, t)
        b2 = lerp(a2, a3, t1, t3, t)
        out.append(lerp(b1, b2, t1, t2, t))
    return out


def dense_loop():
    n = len(CONTROL)
    points = []
    for i in range(n):
        points += catmull_rom(CONTROL[i - 1], CONTROL[i], CONTROL[(i + 1) % n], CONTROL[(i + 2) % n], SAMPLES_PER_SPAN)
    points.append(points[0])
    return points


def resample(points, step):
    """Points every `step` along the polyline's length; the last is the first."""
    out = [points[0]]
    carried = 0.0
    for a, b in zip(points, points[1:]):
        seg = math.dist(a, b)
        pos = step - carried
        while pos <= seg:
            t = pos / seg
            out.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
            pos += step
        carried = seg - (pos - step)
    if math.dist(out[-1], points[0]) < step * 0.5:
        out[-1] = points[0]  # float drift put a last sample on top of the start
    else:
        out.append(points[0])
    return out


def build():
    content = json.loads((ROOT / "site/content.json").read_text())
    labels = content["approach"]["stations"]
    finish = content["approach"]["finish"]
    dense = dense_loop()
    length = sum(math.dist(a, b) for a, b in zip(dense, dense[1:]))
    # A whole number of steps around, so the last step closes the seam exactly.
    step = length / round(length / STEP)
    path = [(round(x, 1), round(y, 1)) for x, y in resample(dense, step)]
    path[-1] = path[0]
    cumulative = [0.0]
    for a, b in zip(path, path[1:]):
        cumulative.append(cumulative[-1] + math.dist(a, b))
    markers = []
    for (sx, sy), label, place in zip(STATIONS, labels, LABEL_PLACEMENT):
        i = min(range(len(path)), key=lambda k: math.dist(path[k], (sx, sy)))
        markers.append({"x": path[i][0], "y": path[i][1], "d": round(cumulative[i], 1), "label": label, **place})
    mapped = [artboard_to_map(x, y) for x, y in path]
    map_d = "M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in mapped)
    map_length = sum(math.dist(a, b) for a, b in zip(mapped, mapped[1:]))
    return path, markers, round(cumulative[-1], 2), map_d, round(map_length, 2), {"x": path[0][0], "y": path[0][1], "label": finish, **FINISH_PLACEMENT}


def main():
    path, markers, length, map_d, map_length, start = build()
    rows = ",\n".join("  " + ", ".join(f"[{x}, {y}]" for x, y in path[i:i + 6]) for i in range(0, len(path), 6))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// GENERATED by scripts/home/make_loop.py — do not edit by hand.\n"
        "/** The \"How I work\" loop in the 1440×800 artboard, clockwise from the start node. */\n"
        f"export const LOOP_PATH = [\n{rows},\n];\n\n"
        f"export const LOOP_STEP = {STEP:g};\n"
        f"export const LOOP_LENGTH = {length};\n\n"
        "/** The four stations, as distances along the path. */\n"
        f"export const LOOP_MARKERS = {json.dumps(markers, ensure_ascii=False)};\n\n"
        "/** Where the loop starts and finishes. */\n"
        f"export const LOOP_START = {json.dumps(start, ensure_ascii=False)};\n\n"
        "/** The same loop in the map SVG's 2560×1440 units. */\n"
        f'export const LOOP_MAP_D = "{map_d}";\n'
        f"export const LOOP_MAP_LENGTH = {map_length};\n"
    )
    print(f"{len(path)} points, length {length}, stations at {[m['d'] for m in markers]}")


if __name__ == "__main__":
    main()
